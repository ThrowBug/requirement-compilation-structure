"""Stage ownership, write scopes, and conservative cross-stage impact rules."""

from pathlib import Path
import json
import re


STAGE_MODULES = {
    "00": "00_project_initialization",
    "01": "01_explore_requirement",
    "02": "02_build_db_schema",
    "03": "03_infer_db_obligations",
    "04": "04_check_db_obligations",
    "05": "05_implement_db",
    "06": "06_design_backend_apis",
    "07": "07_check_backend_apis",
    "08": "08_implement_backend_tdd",
    "09": "09_design_ui",
    "10": "10_implement_ui",
    "11": "11_design_frontend_triggers",
    "12": "12_implement_frontend_tdd",
}

ARTIFACT_OWNERS = {
    ".arc/requirements.json": "01",
    ".arc/db_schema.json": "02",
    ".arc/db_obligations.json": "03",
    ".arc/backend_apis.json": "06",
    ".arc/ui_design.json": "09",
    ".arc/frontend_triggers.json": "11",
}

PROTECTED_PATHS = {
    "frontend/src/ui-runtime.ts",
}

# These files are generated by the compiler and provide the test runner's
# environment. They are readable by implementation tasks, but changing them
# would let a model repair a failing application by changing the test world.
COMPILER_OWNED_PATHS = {
    "backend/scripts/test-api.mjs",
    "backend/tests/support/context.ts",
    "frontend/playwright.e2e.config.ts",
    "frontend/scripts/test-e2e.mjs",
    "frontend/tests/e2e/support/context.ts",
    "frontend/tests/e2e/support/observations.ts",
    "frontend/vite.e2e.config.ts",
}

DATABASE_STAGE_05_PHASES = {
    "SQLite write safety", "fresh initialization", "repeated initialization",
    "missing-table recovery", "compiled initialization", "existing database initialization",
    "output database initialization",
}
DATABASE_STAGE_08_PHASES = {
    "existing server startup", "fresh server startup", "server restart",
}


def normalize_path(path) -> str:
    """Use the portable path form used by snapshots and file tools."""
    value = str(path).replace("\\", "/")
    while value.startswith("./"):
        value = value[2:]
    return value


def stage_number(stage) -> str | None:
    match = re.match(r"^(\d\d)(?:_|$)", str(stage))
    return match.group(1) if match else None


def stage_module(stage) -> str | None:
    number = stage_number(stage) or str(stage)
    return STAGE_MODULES.get(number)


def _indexed_owner(output: Path, path: str) -> str | None:
    index = Path(output) / ".arc/implementation_paths.json"
    if not index.is_file():
        return None
    try:
        value = json.loads(index.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return None
    owners = {
        "api": "08",
        "backend_test": "08",
        "page": "10",
        "trigger": "12",
        "e2e_test": "12",
    }
    for kind, owner in owners.items():
        bucket = value.get(kind, {})
        if isinstance(bucket, dict) and path in bucket.values():
            return owner
    return None


def owner_for_path(output, path) -> str | None:
    """Return the earliest stage that owns a generated source or artifact."""
    path = normalize_path(path)
    if path in ARTIFACT_OWNERS:
        return ARTIFACT_OWNERS[path]
    if path.startswith(".arc/"):
        return None
    if path in PROTECTED_PATHS:
        return "10"
    if indexed := _indexed_owner(output, path):
        return indexed
    if path.startswith("backend/src/db/"):
        return "05"
    if path in {"backend/src/api/register.ts", "backend/src/app.ts", "backend/src/server.ts"}:
        return "08"
    if path.startswith(("backend/src/", "backend/tests/")):
        return "08"
    if path.startswith("frontend/src/triggers/"):
        return "12"
    if path.startswith("frontend/src/"):
        return "10"
    if path.startswith("frontend/tests/e2e/"):
        return "12"
    if path.startswith(("frontend/tests/ui/", "frontend/tests/")):
        return "10"
    return None


def is_compiler_owned(path) -> bool:
    path = normalize_path(path)
    return (path in PROTECTED_PATHS or path in COMPILER_OWNED_PATHS
        or path.startswith(".arc/")
        or path.startswith("frontend/tests/ui/semantic/")
        or "/tests/e2e/acceptance/" in path)


def stage_write_allowed(output, stage, path, *, explicit_paths=(), approved_upstream_paths=()) -> bool:
    """Allow current-stage files and explicitly approved upstream files only."""
    path = normalize_path(path)
    explicit = {normalize_path(item) for item in explicit_paths}
    approved = {normalize_path(item) for item in approved_upstream_paths}
    if is_compiler_owned(path):
        return False
    if path in approved:
        return True
    owner = owner_for_path(output, path)
    current = stage_number(stage)
    if owner is None or current is None:
        return False
    if owner == current:
        return True
    # A task may explicitly claim a source selected by its own stage. This is
    # needed for an interaction task to bind its generated trigger file. It
    # does not grant access to arbitrary paths discovered by the model.
    return path in explicit and owner == current


def classify_changed_paths(output, stage, paths) -> dict:
    """Classify a stage's writes without asking the model to infer ownership."""
    current = stage_number(stage)
    owned, upstream, unknown = [], [], []
    for raw in sorted({normalize_path(path) for path in paths}):
        owner = owner_for_path(output, raw)
        if owner is None:
            unknown.append(raw)
        elif owner == current:
            owned.append(raw)
        else:
            upstream.append({"path": raw, "owner_stage": owner, "owner_module": stage_module(owner)})
    return {"stage": current, "owned": owned, "upstream": upstream, "unknown": unknown}


def upstream_repair_request(output, stage, paths, reason, *, contract_changed=False, check=None) -> dict | None:
    classification = classify_changed_paths(output, stage, paths)
    if not classification["upstream"]:
        return None
    owners = sorted({item["owner_stage"] for item in classification["upstream"]})
    request = {
        "status": "PENDING",
        "current_stage": stage_number(stage),
        "current_module": stage_module(stage),
        "owner_stage": owners[0],
        "owner_module": stage_module(owners[0]),
        "changed_paths": [item["path"] for item in classification["upstream"]],
        "owners": classification["upstream"],
        "reason": reason,
        "contract_changed": bool(contract_changed),
    }
    if check:
        request["failed_check"] = check
    return request


def repair_request_for_owner(stage, owner, paths, reason, *, contract_changed=False, check=None) -> dict:
    """Create a request when a deterministic check identifies an earlier owner."""
    owner = stage_number(owner)
    request = {
        "status": "PENDING",
        "current_stage": stage_number(stage),
        "current_module": stage_module(stage),
        "owner_stage": owner,
        "owner_module": stage_module(owner),
        "changed_paths": sorted({normalize_path(path) for path in paths}),
        "reason": reason,
        "contract_changed": bool(contract_changed),
    }
    if check:
        request["failed_check"] = check
    return request


def database_failure_owner(result):
    """Return a stage owner only for a database check phase with clear ownership."""
    phase = result.get("phase") if isinstance(result, dict) else None
    if phase in DATABASE_STAGE_05_PHASES:
        return "05", ["backend/src/db/initialize.ts", "backend/src/db/setup.ts"]
    if phase in DATABASE_STAGE_08_PHASES:
        return "08", ["backend/src/api/register.ts", "backend/src/app.ts", "backend/src/server.ts"]
    return None


def rerun_modules_for_request(request, completed_modules) -> list[str]:
    """Return the smallest ordered suffix needed for an upstream repair."""
    if not request:
        return []
    owner = stage_number(request.get("owner_stage"))
    if owner is None:
        return sorted(completed_modules)
    modules = sorted(completed_modules, key=lambda item: int(stage_number(item) or 99))
    start = next((index for index, module in enumerate(modules)
        if stage_number(module) == owner), None)
    if start is None:
        return modules
    return modules[start:]


def validation_modules_for_paths(output, paths, *, contract_changed=False) -> list[str]:
    """Choose implementation checks without regenerating unrelated designs."""
    owners = {owner_for_path(output, path) for path in paths}
    owners.discard(None)
    if not owners:
        return []
    if contract_changed:
        first = min(int(owner) for owner in owners)
        return [module for number, module in STAGE_MODULES.items() if int(number) >= first]
    selected = set()
    for owner in owners:
        if owner == "05":
            selected.update(("05", "08", "12"))
        elif owner == "08":
            selected.update(("08", "12"))
        elif owner == "10":
            selected.update(("10", "12"))
        elif owner == "12":
            selected.add("12")
        else:
            selected.update(number for number in STAGE_MODULES if int(number) >= int(owner))
    return [STAGE_MODULES[number] for number in sorted(selected, key=int)]
